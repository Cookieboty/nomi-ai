import os from 'os';
import path from 'path';

import type { ClientModels } from '@nomi-ai/gateway';

import { t as tr } from '../i18n';
import { guardedHandle } from '../security/guardedIpc';
import { shQuote } from '../security/shellEscape';
import { ensurePrivateDir, writePrivateFile } from '../utils/privateFile';

import { agentLaunch, type AgentKind, type AgentLaunch, type ModelMeta } from './agents';
import type { GatewayService } from './GatewayService';
import { updateWindowsPath } from './windowsPath';
import { buildWindowsRunner } from './windowsTerminal';

type Logger = { info(m: string, d?: unknown): void; warn(m: string, d?: unknown): void };

export const TERMINAL_KINDS: readonly AgentKind[] = ['claude', 'codex', 'gemini', 'grok', 'dsh'];

/** 生成脚本时代替令牌 / 模型的占位符：令牌运行时读文件，模型可被 --nomi-model 覆盖 */
const TOKEN_MARK = '__NOMI_TOKEN__';
const MODEL_MARK = '__NOMI_MODEL__';

export const RC_BEGIN = '# >>> Nomi terminal commands >>>';
export const RC_END = '# <<< Nomi terminal commands <<<';

export interface TerminalSource {
  /** 网关地址（http://127.0.0.1:端口，不带 /v1） */
  url: string;
  clients: Partial<Record<AgentKind, { token: string | null; models: ClientModels }>>;
  metaOf?: (ref: string) => ModelMeta | undefined;
  catalog?: string[];
}

export interface TerminalDeps {
  /** userData/gateway */
  root: string;
  /** 当前网关地址、各 CLI 的令牌与模型分配；拿不到时返回 null（不生成） */
  source: () => TerminalSource | null;
  logger?: Logger;
  /** 测试注入 */
  home?: string;
  platform?: NodeJS.Platform;
  shell?: string;
  windowsPath?: typeof updateWindowsPath;
}

interface Persisted {
  enabled: boolean;
  pathAdded: boolean;
  windowsPathOwned?: boolean;
  /** 加过 PATH 段的文件（关闭时据此删除；同时也扫一遍候选文件） */
  rcFiles?: string[];
}

export interface TerminalStateView {
  enabled: boolean;
  pathAdded: boolean;
  binDir: string;
  /** 会写入（或已写入）PATH 段的 shell 配置文件 */
  rcFiles: string[];
  /** 当前平台是否支持自动加入 PATH */
  pathSupported: boolean;
  pathKind?: 'user-path' | 'shell-rc';
  /** 生成的命令名（Windows 带 .cmd） */
  commands: string[];
}

/* ------------------------------ 脚本生成 ------------------------------ */

export interface ScriptInput {
  kind: AgentKind;
  platform: NodeJS.Platform;
  url: string;
  tokenFile: string;
  /** 默认模型（clients.<cli>.models.main）；null 时生成只提示「先设置模型」的脚本 */
  model: string | null;
  /** agentLaunch 的结果（令牌是 TOKEN_MARK，模型是 model） */
  launch?: AgentLaunch;
  /** Grok 覆盖模型时用的配置模板（模型处是 MODEL_MARK）；dsh 的叠加文件模板 */
  template?: string;
}

/** 在 Nomi 外直接运行这些命令时要执行的真实 CLI */
const BIN: Record<AgentKind, string> = {
  claude: 'claude',
  codex: 'codex',
  gemini: 'gemini',
  grok: 'grok',
  dsh: 'dsh',
};

export const commandName = (kind: AgentKind, platform: NodeJS.Platform = process.platform) =>
  `nomi-${kind}${platform === 'win32' ? '.cmd' : ''}`;

/** 模型名只允许这些字符（脚本里要拼进 TOML / sed） */
const MODEL_RE_SH = '*[!A-Za-z0-9._:/@+-]*';

/** 环境变量的值：令牌 / 默认模型在运行时代入，其余是静态值 */
type EnvValue = { kind: 'token' } | { kind: 'model' } | { kind: 'static'; value: string };

function envValues(launch: AgentLaunch, model: string): Array<[string, EnvValue]> {
  return Object.entries(launch.env).map(([k, v]) => {
    if (v.includes(TOKEN_MARK)) return [k, { kind: 'token' }];
    if (v === model) return [k, { kind: 'model' }];
    return [k, { kind: 'static', value: v }];
  });
}

/** 只含安全字符的参数不加引号（脚本更好读），其余单引号包起来 */
const shArg = (s: string) => (/^[A-Za-z0-9_@%+=:,./-]+$/.test(s) ? s : shQuote(s));

const header = (kind: AgentKind) =>
  `Generated by Nomi for "${kind}" (third-party models via the Nomi gateway). ` +
  'Regenerated automatically; edits are overwritten.';

function posixScript(i: ScriptInput): string {
  const bin = BIN[i.kind];
  const say = (msg: string) => `printf '%s\\n' ${shQuote(msg)} >&2`;
  const L: string[] = ['#!/bin/sh', `# ${header(i.kind)}`];
  if (!i.model || !i.launch) {
    L.push(say(tr('还没有为 {0} 设置第三方模型：请在 Nomi 设置 → 模型 里选择。', bin)), 'exit 1');
    return L.join('\n') + '\n';
  }
  const launch = i.launch;
  const needModel = say(tr('--nomi-model 后面要跟 供应商/模型'));
  const badModel = say(tr('模型名无效：'));
  const down = say(tr('请先打开 Nomi：网关（{0}）没有响应。', i.url));
  const noToken = say(tr('找不到令牌：请在 Nomi 设置 → 模型 里重新打开「终端启动命令」。'));
  const noBin = say(tr('没有找到 {0}：请先安装。', bin));
  L.push(
    `NOMI_URL=${shQuote(i.url)}`,
    `NOMI_TOKEN_FILE=${shQuote(i.tokenFile)}`,
    `NOMI_DEFAULT_MODEL=${shQuote(i.model)}`,
    'NOMI_MODEL=$NOMI_DEFAULT_MODEL',
    'NOMI_DOWN=',
    '',
    '# --nomi-model provider/model overrides the model; every other argument is passed through',
    'n=$#',
    'while [ "$n" -gt 0 ]; do',
    '  a=$1; shift; n=$((n - 1))',
    '  case $a in',
    '    --nomi-model)',
    `      if [ "$n" -eq 0 ]; then ${needModel}; exit 2; fi`,
    '      NOMI_MODEL=$1; shift; n=$((n - 1)) ;;',
    '    --nomi-model=*) NOMI_MODEL=${a#--nomi-model=} ;;',
    '    *) set -- "$@" "$a" ;;',
    '  esac',
    'done',
    'case $NOMI_MODEL in',
    `  ''|${MODEL_RE_SH}) ${badModel}; printf '%s\\n' "$NOMI_MODEL" >&2; exit 2 ;;`,
    'esac',
    '',
    '# Is Nomi (the gateway) running?',
    'if command -v curl >/dev/null 2>&1; then',
    '  curl -fsS -m 3 "$NOMI_URL/health" >/dev/null 2>&1 || NOMI_DOWN=1',
    'elif command -v wget >/dev/null 2>&1; then',
    '  wget -q -T 3 -O /dev/null "$NOMI_URL/health" >/dev/null 2>&1 || NOMI_DOWN=1',
    'fi',
    'if [ -n "$NOMI_DOWN" ]; then',
    `  ${down}`,
    '  exit 1',
    'fi',
    'if [ ! -r "$NOMI_TOKEN_FILE" ]; then',
    `  ${noToken}`,
    '  exit 1',
    'fi',
    'NOMI_TOKEN=$(cat "$NOMI_TOKEN_FILE")',
    `if ! command -v ${bin} >/dev/null 2>&1; then`,
    `  ${noBin}`,
    '  exit 127',
    'fi',
    '',
  );
  if (launch.strip.length) L.push(`unset ${launch.strip.join(' ')}`);
  for (const [k, v] of envValues(launch, i.model)) {
    if (v.kind === 'token') L.push(`export ${k}="$NOMI_TOKEN"`);
    else if (v.kind === 'model') L.push(`export ${k}="$NOMI_MODEL"`);
    else L.push(`export ${k}=${shQuote(v.value)}`);
  }

  const args = launch.args.map(shArg);
  if (i.kind === 'claude') args.push('--model', '"$NOMI_MODEL"');
  if (i.kind === 'codex') args.push('-c', '"model=\\"$NOMI_MODEL\\""');
  // Grok / dsh 的模型写在配置文件里：覆盖时按模板在旁边生成一份
  const slug = `$(printf '%s' "$NOMI_MODEL" | tr -c 'A-Za-z0-9._-' '_')`;
  if (i.kind === 'dsh' && i.template) {
    const patchAt = launch.args.indexOf('--patch') + 1;
    const base = launch.args[patchAt] ?? '';
    L.push(
      `NOMI_PATCH=${shQuote(base)}`,
      'if [ "$NOMI_MODEL" != "$NOMI_DEFAULT_MODEL" ]; then',
      `  NOMI_PATCH=${shQuote(`${path.dirname(base)}/override-`)}${slug}.yml`,
      `  sed "s|${MODEL_MARK}|$NOMI_MODEL|g" ${shQuote(i.template)} > "$NOMI_PATCH" || exit 1`,
      '  chmod 600 "$NOMI_PATCH"',
      'fi',
    );
    if (patchAt > 0) args[patchAt] = '"$NOMI_PATCH"';
  }
  if (i.kind === 'grok' && i.template) {
    const home = launch.env.GROK_HOME ?? '';
    L.push(
      'if [ "$NOMI_MODEL" != "$NOMI_DEFAULT_MODEL" ]; then',
      `  NOMI_HOME=${shQuote(`${home}-models/`)}${slug}`,
      '  mkdir -p "$NOMI_HOME" && chmod 700 "$NOMI_HOME" || exit 1',
      // 私有目录里的软链（sessions 等）照搬，config.toml 按模板换模型
      `  for f in ${shQuote(home)}/* ${shQuote(home)}/.[!.]*; do`,
      '    [ -e "$f" ] || [ -L "$f" ] || continue',
      '    b=${f##*/}',
      '    [ "$b" = config.toml ] && continue',
      '    [ -e "$NOMI_HOME/$b" ] || [ -L "$NOMI_HOME/$b" ] && continue',
      '    t=$(readlink "$f" 2>/dev/null) || t=$f',
      '    ln -s "$t" "$NOMI_HOME/$b" 2>/dev/null',
      '  done',
      `  sed "s|${MODEL_MARK}|$NOMI_MODEL|g" ${shQuote(i.template)} > "$NOMI_HOME/config.toml" || exit 1`,
      '  chmod 600 "$NOMI_HOME/config.toml"',
      '  export GROK_HOME="$NOMI_HOME"',
      'fi',
    );
  }
  L.push(`exec ${[bin, ...args].join(' ')} "$@"`);
  return L.join('\n') + '\n';
}

function cmdScript(i: ScriptInput): string {
  return [
    '@echo off',
    `rem ${header(i.kind)}`,
    'setlocal DisableDelayedExpansion',
    `node.exe "%~dp0nomi-runner.cjs" "%~dp0nomi-${i.kind}.json" %*`,
    'exit /b %ERRORLEVEL%',
    '',
  ].join('\r\n');
}

function powershellScript(kind: AgentKind): string {
  // Windows PowerShell 5 会在传给原生程序时损坏引号 / 空参数；通过环境中的 JSON 传 argv。
  return [
    `# ${header(kind)}`,
    '$nomiPreviousArgs = $env:NOMI_TERMINAL_ARGS',
    'try {',
    '  $env:NOMI_TERMINAL_ARGS = ConvertTo-Json -InputObject @($args) -Compress',
    `  & node.exe (Join-Path $PSScriptRoot 'nomi-runner.cjs') (Join-Path $PSScriptRoot 'nomi-${kind}.json') --nomi-powershell-args`,
    '  $nomiExitCode = $LASTEXITCODE',
    '} finally {',
    '  $env:NOMI_TERMINAL_ARGS = $nomiPreviousArgs',
    '}',
    'exit $nomiExitCode',
    '',
  ].join('\r\n');
}

/** 一个 CLI 的启动脚本内容（纯函数，便于测试） */
export function buildScript(i: ScriptInput): string {
  return i.platform === 'win32' ? cmdScript(i) : posixScript(i);
}

/* ------------------------------ shell 配置文件里的 PATH 段 ------------------------------ */

export type RcShell = 'posix' | 'fish';

/** 加上带标记的一段（已有则先去掉再加，结果幂等）；其它内容原样保留 */
export function addRcBlock(content: string, shell: RcShell): string {
  const line =
    shell === 'fish' ? 'set -gx PATH $HOME/.nomi/bin $PATH' : 'export PATH="$HOME/.nomi/bin:$PATH"';
  const kept = removeRcBlock(content);
  const sep = kept === '' || kept.endsWith('\n') ? '' : '\n';
  return `${kept}${sep}${RC_BEGIN}\n# Added by Nomi; removed when terminal commands are turned off.\n${line}\n${RC_END}\n`;
}

/** 去掉带标记的那一段（含它前面 addRcBlock 加的空行之外，其余内容不动） */
export function removeRcBlock(content: string): string {
  const lines = content.split('\n');
  const out: string[] = [];
  let inBlock = false;
  for (const l of lines) {
    if (!inBlock && l.trim() === RC_BEGIN) {
      inBlock = true;
      continue;
    }
    if (inBlock) {
      if (l.trim() === RC_END) inBlock = false;
      continue;
    }
    out.push(l);
  }
  // 没找到结束标记：不改（不冒险删掉用户内容）
  if (inBlock) return content;
  return out.join('\n');
}

/* ------------------------------ 服务 ------------------------------ */

export class TerminalCommands {
  private readonly home: string;
  private readonly platform: NodeJS.Platform;
  private readonly stateFile: string;
  readonly binDir: string;
  readonly tokenDir: string;
  readonly workDir: string;
  private st: Persisted;

  constructor(private readonly d: TerminalDeps) {
    this.home = d.home ?? os.homedir();
    this.platform = d.platform ?? process.platform;
    this.stateFile = path.join(d.root, 'terminal.json');
    this.binDir = path.join(this.home, '.nomi', 'bin');
    this.tokenDir = path.join(d.root, 'tokens');
    this.workDir = path.join(d.root, 'terminal');
    this.st = this.load();
  }

  private load(): Persisted {
    try {
      const raw = JSON.parse(fs.readFileSync(this.stateFile, 'utf8')) as Partial<Persisted>;
      return {
        enabled: raw.enabled === true,
        pathAdded: raw.pathAdded === true,
        windowsPathOwned: raw.windowsPathOwned === true,
        ...(Array.isArray(raw.rcFiles) ? { rcFiles: raw.rcFiles.map(String) } : {}),
      };
    } catch {
      return { enabled: false, pathAdded: false };
    }
  }

  private save(): void {
    fs.mkdirSync(this.d.root, { recursive: true, mode: 0o700 });
    writePrivateFile(this.stateFile, JSON.stringify(this.st, null, 2));
  }

  private get pathSupported(): boolean {
    return true;
  }

  /** 会写 PATH 段的文件：已存在的 zsh / bash / fish 配置；都没有时按登录 shell 选一个 */
  rcCandidates(): Array<{ file: string; shell: RcShell }> {
    const h = this.home;
    const all: Array<{ file: string; shell: RcShell }> = [
      { file: path.join(h, '.zshrc'), shell: 'posix' },
      { file: path.join(h, '.bashrc'), shell: 'posix' },
      { file: path.join(h, '.config', 'fish', 'config.fish'), shell: 'fish' },
    ];
    const present = all.filter((c) => fs.existsSync(c.file));
    if (present.length) return present;
    const sh = path.basename(this.d.shell ?? process.env.SHELL ?? '');
    if (sh === 'fish') return [all[2]!];
    if (sh === 'bash')
      return [
        this.platform === 'darwin'
          ? { file: path.join(h, '.bash_profile'), shell: 'posix' }
          : all[1]!,
      ];
    if (sh === 'zsh' || this.platform === 'darwin') return [all[0]!];
    return [{ file: path.join(h, '.profile'), shell: 'posix' }];
  }

  state(): TerminalStateView {
    return {
      enabled: this.st.enabled,
      pathAdded: this.st.pathAdded,
      binDir: this.binDir,
      rcFiles:
        this.platform !== 'win32'
          ? this.st.pathAdded && this.st.rcFiles?.length
            ? this.st.rcFiles
            : this.rcCandidates().map((c) => c.file)
          : [],
      pathSupported: this.pathSupported,
      pathKind: this.platform === 'win32' ? 'user-path' : 'shell-rc',
      commands: TERMINAL_KINDS.flatMap((k) =>
        this.platform === 'win32'
          ? [commandName(k, this.platform), `nomi-${k}.ps1`]
          : [commandName(k, this.platform)],
      ),
    };
  }

  /** 开关；addToPath 省略时保持现状，true 加 PATH 段（界面已确认），false 去掉 */
  set(input: { enabled: boolean; addToPath?: boolean }): TerminalStateView {
    if (input.enabled) {
      this.st.enabled = true;
      this.save();
      this.refresh();
      if (input.addToPath === true && this.pathSupported) this.addPath();
      else if (input.addToPath === false) this.removePath();
    } else {
      this.st.enabled = false;
      this.removePath();
      this.removeGenerated();
      this.save();
    }
    return this.state();
  }

  /** 网关端口 / 令牌 / 模型分配变化后重新生成（关闭时什么都不做） */
  refresh(): void {
    if (!this.st.enabled) return;
    try {
      this.generate();
    } catch (e) {
      this.d.logger?.warn('terminal commands: generate failed', e);
    }
  }

  private generate(): void {
    const src = this.d.source();
    if (!src) return;
    fs.mkdirSync(this.binDir, { recursive: true });
    ensurePrivateDir(this.tokenDir);
    fs.mkdirSync(this.workDir, { recursive: true, mode: 0o700 });
    if (this.platform === 'win32')
      writeIfChanged(path.join(this.binDir, 'nomi-runner.cjs'), buildWindowsRunner(), 0o600);
    for (const kind of TERMINAL_KINDS) {
      const client = src.clients[kind];
      const tokenFile = path.join(this.tokenDir, kind);
      if (client?.token) writeIfChanged(tokenFile, client.token, 0o600);
      else rmQuiet(tokenFile);
      const model = client?.models.main ?? null;
      let launch: AgentLaunch | undefined;
      let template: string | undefined;
      if (model && client) {
        const ctx = {
          url: src.url,
          token: TOKEN_MARK,
          model,
          models: client.models,
          dir: path.join(this.workDir, kind),
          ...(src.metaOf ? { metaOf: src.metaOf } : {}),
          ...(src.catalog ? { catalog: src.catalog } : {}),
          home: this.home,
        };
        launch = agentLaunch(kind, ctx);
        template = this.template(kind, ctx);
      }
      const file = path.join(this.binDir, commandName(kind, this.platform));
      const content = buildScript({
        kind,
        platform: this.platform,
        url: src.url,
        tokenFile,
        model,
        ...(launch ? { launch } : {}),
        ...(template ? { template } : {}),
      });
      writeIfChanged(file, content, 0o755);
      if (this.platform === 'win32') {
        const config: ScriptInput = {
          kind,
          platform: this.platform,
          url: src.url,
          tokenFile,
          model,
          launch,
          template,
        };
        writePrivateFile(
          path.join(this.binDir, `nomi-${kind}.json`),
          JSON.stringify({
            ...config,
            messages: {
              noModel: tr('还没有为 {0} 设置第三方模型：请在 Nomi 设置 → 模型 里选择。', kind),
              needModel: tr('--nomi-model 后面要跟 供应商/模型'),
              badModel: tr('模型名无效：'),
              down: tr('请先打开 Nomi：网关（{0}）没有响应。', src.url),
              noToken: tr('找不到令牌：请在 Nomi 设置 → 模型 里重新打开「终端启动命令」。'),
              noBin: tr('没有找到 {0}：请先安装。', kind),
              unsafeShim: tr('无法安全启动 {0}：请重新安装 CLI，或使用它的原生可执行文件。', kind),
            },
          }),
        );
        writeIfChanged(path.join(this.binDir, `nomi-${kind}.ps1`), powershellScript(kind), 0o755);
      }
    }
  }

  /** Grok / dsh 覆盖模型时的配置模板（模型处为 MODEL_MARK） */
  private template(kind: AgentKind, ctx: Parameters<typeof agentLaunch>[1]): string | undefined {
    if (kind !== 'grok' && kind !== 'dsh') return undefined;
    const dir = path.join(this.workDir, 'templates');
    fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
    if (kind === 'dsh') {
      const tdir = path.join(dir, 'dsh');
      agentLaunch('dsh', { ...ctx, model: MODEL_MARK, dir: tdir });
      return path.join(tdir, 'patch.yml');
    }
    const cfg = fs.readFileSync(path.join(ctx.dir, 'config.toml'), 'utf8');
    const file = path.join(dir, 'grok.config.toml');
    writePrivateFile(file, cfg.replace(/^model = .*$/m, `model = "${MODEL_MARK}"`));
    return file;
  }

  private removeGenerated(): void {
    for (const kind of TERMINAL_KINDS) {
      rmQuiet(path.join(this.binDir, commandName(kind, this.platform)));
      if (this.platform === 'win32') {
        rmQuiet(path.join(this.binDir, `nomi-${kind}.ps1`));
        rmQuiet(path.join(this.binDir, `nomi-${kind}.json`));
      }
      rmQuiet(path.join(this.tokenDir, kind));
    }
    if (this.platform === 'win32') rmQuiet(path.join(this.binDir, 'nomi-runner.cjs'));
    // 私有目录里只有软链和 Nomi 生成的文件；rm 不跟随软链，~/.grok 等不受影响
    fs.rmSync(this.workDir, { recursive: true, force: true });
    for (const dir of [this.binDir, this.tokenDir, path.dirname(this.binDir)]) {
      try {
        fs.rmdirSync(dir);
      } catch {
        /* 非空或不存在：保留 */
      }
    }
  }

  private addPath(): void {
    if (this.platform === 'win32') {
      const added = (this.d.windowsPath ?? updateWindowsPath)(this.binDir, true);
      this.st.windowsPathOwned = this.st.windowsPathOwned || added;
      this.st.pathAdded = true;
      this.save();
      return;
    }
    const done: string[] = [];
    for (const c of this.rcCandidates()) {
      try {
        const cur = fs.existsSync(c.file) ? fs.readFileSync(c.file, 'utf8') : '';
        const next = addRcBlock(cur, c.shell);
        if (next !== cur) {
          fs.mkdirSync(path.dirname(c.file), { recursive: true });
          fs.writeFileSync(c.file, next);
        }
        done.push(c.file);
      } catch (e) {
        this.d.logger?.warn('terminal commands: add PATH failed', { file: c.file, e });
      }
    }
    this.st.pathAdded = done.length > 0;
    this.st.rcFiles = done;
    this.save();
  }

  private removePath(): void {
    if (this.platform === 'win32') {
      if (this.st.windowsPathOwned) (this.d.windowsPath ?? updateWindowsPath)(this.binDir, false);
      this.st.pathAdded = false;
      delete this.st.windowsPathOwned;
      this.save();
      return;
    }
    const files = new Set([
      ...(this.st.rcFiles ?? []),
      ...this.rcCandidates().map((c) => c.file),
      path.join(this.home, '.zshrc'),
      path.join(this.home, '.bashrc'),
      path.join(this.home, '.bash_profile'),
      path.join(this.home, '.profile'),
      path.join(this.home, '.config', 'fish', 'config.fish'),
    ]);
    for (const file of files) {
      try {
        if (!fs.existsSync(file)) continue;
        const cur = fs.readFileSync(file, 'utf8');
        const next = removeRcBlock(cur);
        if (next !== cur) fs.writeFileSync(file, next);
      } catch (e) {
        this.d.logger?.warn('terminal commands: remove PATH failed', { file, e });
      }
    }
    this.st.pathAdded = false;
    delete this.st.rcFiles;
    this.save();
  }
}

function writeIfChanged(file: string, data: string, mode: number): void {
  try {
    if (fs.readFileSync(file, 'utf8') === data) {
      fs.chmodSync(file, mode);
      return;
    }
  } catch {
    /* 不存在 */
  }
  if (mode === 0o600) writePrivateFile(file, data);
  else {
    fs.writeFileSync(file, data, { mode });
    try {
      fs.chmodSync(file, mode);
    } catch {
      /* Windows 忽略 */
    }
  }
}

function rmQuiet(file: string): void {
  try {
    fs.rmSync(file, { force: true });
  } catch {
    /* 忽略 */
  }
}

