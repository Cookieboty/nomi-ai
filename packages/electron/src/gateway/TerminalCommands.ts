/** 从网关服务取脚本需要的数据；网关没在运行时用配置的端口（脚本运行时自己查 /health） */
export function gatewayTerminalSource(g: GatewayService): () => TerminalSource | null {
  return () => {
    const s = g.status();
    const snap = g.store.snapshot();
    const port = s.state === 'running' ? s.port : snap.port;
    if (!port) return null;
    const providers = g.store.providers();
    const metaOf = (ref: string): ModelMeta | undefined => {
      const i = ref.indexOf('/');
      const p = i > 0 ? providers.find((x) => x.id === ref.slice(0, i)) : undefined;
      const m = p?.models.find((x) => x.id === ref.slice(i + 1));
      return p && m
        ? {
            label: m.label ?? m.id,
            provider: p.name,
            ctx: m.ctx,
            maxOutput: m.maxOutput,
            reasoning: m.reasoning,
            vision: m.vision,
          }
        : undefined;
    };
    const clients: TerminalSource['clients'] = {};
    for (const kind of TERMINAL_KINDS)
      clients[kind] = {
        token: g.store.clientToken(kind),
        models: snap.clients[kind]?.models ?? {},
      };
    return {
      url: `http://127.0.0.1:${port}`,
      clients,
      metaOf,
      catalog: g.cliModels().map((m) => m.ref),
    };
  };
}

