#!/usr/bin/env node
/**
 * Edge TTS 时间串（JSDateString）时区 golden：2024-01-01 ~ 2037-12-31 窗口内，每个 IANA 区
 * 在 Electron 44.9.3（ICU 78.2 / 其内置 tzdata）下的 (偏移, 括号名) 分段。
 * 字符串只用于“当前时刻”，故只覆盖现在与未来；2024 前不在范围（见设计文档 D-B9-4）。
 * 逐日扫描 + 二分到秒定位每个变化点，再在 Electron 内用每变化点 ±48h 逐小时 + 2000 个随机时刻自检分段模型。
 * Usage: TZ=UTC ELECTRON_RUN_AS_NODE=1 electron scripts/parity/record-tz-window.mjs
 *   && gofmt -w apps/desktop-go/internal/core/tts/edge/zonewindow_gen.go
 *   → edge/testdata/tz-window.json（测试 golden）+ edge/zonewindow_gen.go（运行时内嵌表）
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const T0 = Date.UTC(2024, 0, 1) / 1000, T1 = Date.UTC(2038, 0, 1) / 1000 - 1;
// 区名集合与 gen-tz-names.mjs 相同：Intl 规范名 + 本机 /usr/share/zoneinfo 下全部 TZif（含别名，如 US/Eastern、Asia/Calcutta）
const zoneSet = new Set(Intl.supportedValuesOf('timeZone'));
zoneSet.add('UTC');
const walk = (d, pre) => {
  for (const f of readdirSync(d)) {
    if (/^(posix|right|SystemV)$/.test(f) || /\.(tab|zi|list)$/.test(f) || /^[a-z+]/.test(f)) continue;
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p, pre + f + '/');
    else if (readFileSync(p).subarray(0, 4).toString() === 'TZif') zoneSet.add(pre + f);
  }
};
try { walk('/usr/share/zoneinfo', ''); } catch {}
const zones = [...zoneSet];
let s = 20240101;
const rnd = () => (s = (s * 1103515245 + 12345) % 2147483648) / 2147483648;
const random = Array.from({ length: 2000 }, () => T0 + Math.floor(rnd() * (T1 - T0)));

const probe = `
const T0=${T0},T1=${T1},R=${JSON.stringify(random)};
const k=t=>{const d=new Date(t*1000);return -d.getTimezoneOffset()+'|'+d.toString().replace(/^.*\\((.*)\\)$/,'$1')};
const seg=[[T0,k(T0)]];
for(let t=T0+86400;t<=T1+86400;t+=86400){const u=Math.min(t,T1);if(k(u)!==seg[seg.length-1][1]){let lo=t-86400,hi=u;while(hi-lo>1){const m=Math.floor((lo+hi)/2);k(m)===k(lo)?lo=m:hi=m}seg.push([hi,k(hi)])}}
const at=t=>{let v=seg[0][1];for(const x of seg)if(x[0]<=t)v=x[1];return v};
const chk=[...R];for(const [b] of seg.slice(1))for(let h=-48;h<=48;h++)chk.push(b+h*3600,b-1);
for(const t of chk)if(t>=T0&&t<=T1&&k(t)!==at(t))throw new Error('segment model miss '+process.env.TZ+' '+t);
process.stdout.write(JSON.stringify(seg.map(([t,v])=>{const i=v.indexOf('|');return [t,+v.slice(0,i),v.slice(i+1)]})));`;
const out = {};
for (const z of zones.sort()) {
  try { out[z] = JSON.parse(execFileSync(process.execPath, ['-e', probe], { env: { ...process.env, TZ: z } }).toString()); }
  catch (e) { if (/segment model miss/.test(String(e.stderr))) throw e; }
}
const lines = Object.entries(out).map(([z, v]) => `    ${JSON.stringify(z)}: ${JSON.stringify(v)}`);
writeFileSync(join(root, 'apps/desktop-go/internal/core/tts/edge/testdata/tz-window.json'),
  `{\n  "runtime": ${JSON.stringify(`node ${process.version} icu ${process.versions.icu} tz ${process.versions.tz}`)},\n  "from": ${T0}, "to": ${T1},\n  "random": ${JSON.stringify(random)},\n  "zones": {\n${lines.join(',\n')}\n  }\n}\n`);

// 同时生成 Go 内嵌表：窗口内直接用 Electron 的偏移+名（Go 自带/系统 tzdata 可能较旧，如 2026 起
// America/Vancouver、Edmonton 规则变化），保证与 2.0.4 的输出逐字一致。
const goRows = Object.entries(out).map(([z, v]) => `\t${JSON.stringify(z)}: ${JSON.stringify(v.map(([t, o, n]) => `${t} ${o} ${n}`).join('|'))},`);
writeFileSync(join(root, 'apps/desktop-go/internal/core/tts/edge/zonewindow_gen.go'),
  `// Code generated by scripts/parity/record-tz-window.mjs; DO NOT EDIT.\n// ${`node ${process.version} icu ${process.versions.icu} tz ${process.versions.tz}`} (Electron 44.9.3)\n\npackage edge\n\nconst zoneWindowFrom, zoneWindowTo = ${T0}, ${T1}\n\n// zoneWindow：IANA 区 → "起始unix秒 偏移分钟 括号名|…"\nvar zoneWindow = map[string]string{\n${goRows.join('\n')}\n}\n`);
