#!/usr/bin/env node
/** 灵动岛几何与页面（Node 录制）：
 *  1) golden → apps/desktop-go/internal/core/island/testdata/geometry.json：islandGeometry / clampIslandHeight /
 *     islandWindowRect / islandHtml（geometry.ts、islandPage.ts 纯模块，直接 import）。
 *  2) 生成 apps/desktop-go/internal/core/island/islandpage_tpl.go：用哨兵几何调用真实 islandHtml，
 *     得到刘海 / 胶囊两份逐字模板，Go 只替换哨兵（不手抄页面），golden 再逐字比对整页。
 *  用法：pnpm exec tsx scripts/parity/record-island-geometry.mjs */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const geo = await import(
  pathToFileURL(join(root, 'apps/desktop-electron/src/island/geometry.ts')).href
);
const { islandHtml } = await import(
  pathToFileURL(join(root, 'apps/desktop-electron/src/island/islandPage.ts')).href
);

// —— 模板：数值字段换成哨兵字符串；JS 里的 g.inset + g.pad.top + g.pad.bottom 会拼成三个哨兵相连
const S = (k) => `\u27e6${k}\u27e7`;
const tpl = {};
for (const mode of ['notch', 'pill']) {
  const g = {
    mode,
    x: S('x'),
    y: S('y'),
    width: S('width'),
    height: S('height'),
    collapsed: { width: S('cw'), height: S('ch') },
    menuBarHeight: S('mb'),
    inset: S('inset'),
    pad: { top: S('padT'), bottom: S('padB') },
    rowMin: S('rowMin'),
    margin: { x: S('mx'), bottom: S('mb2') },
  };
  tpl[mode] = islandHtml(g)
    .split(S('inset') + S('padT') + S('padB'))
    .join(S('base'));
}
const goFile = `// Code generated by scripts/parity/record-island-geometry.mjs from islandPage.ts; DO NOT EDIT.

package island

// islandPageTpl：islandHtml(g) 的逐字模板，⟦字段⟧ 为几何数值哨兵，⟦base⟧ = inset+pad.top+pad.bottom
var islandPageTpl = map[string]string{
	"notch": ${JSON.stringify(tpl.notch)},
	"pill":  ${JSON.stringify(tpl.pill)},
}
`;
writeFileSync(join(root, 'apps/desktop-go/internal/core/island/islandpage_tpl.go'), goFile);

// —— golden
const displays = [];
for (const [w, h] of [
  [1512, 982],
  [1728, 1117],
  [1920, 1080],
  [2560, 1440],
  [1280, 800],
  [430, 932],
  [300, 600],
  [33, 100],
  [1366.5, 768],
])
  for (const mb of [0, 24, 25, 30, 37, 38.5])
    for (const [bx, by] of [
      [0, 0],
      [-1920, 0],
      [1512, -200],
    ])
      displays.push({
        bounds: { x: bx, y: by, width: w, height: h },
        workArea: { x: bx, y: by + mb, width: w, height: h - mb },
      });
displays.push({
  bounds: { x: 0, y: 0, width: 1512, height: 982 },
  workArea: { x: 0, y: 37, width: 1512, height: 945 },
  internal: false,
});
const measures = [0, 1, 18, 33, 40, 55.2, 60, 61.4, 80, 100, 137, 500, -5, NaN, Infinity];
const cases = [],
  pages = {};
for (const plat of ['darwin', 'linux', 'win32'])
  for (const d of displays)
    for (const pref of ['auto', 'pill']) {
      const g = geo.islandGeometry(plat, d, pref);
      const key = JSON.stringify(g);
      // 整页逐字比对：每种模式取前 24 个不同几何（页面只在数值上不同）
      if (!pages[key] && Object.values(pages).filter((p) => p.mode === g.mode).length < 24)
        pages[key] = { mode: g.mode, html: islandHtml(g) };
      cases.push({
        plat,
        display: d,
        pref,
        g,
        rect: geo.islandWindowRect(g, g.height),
        clamp: measures.map((m) => {
          const h = geo.clampIslandHeight(g, m);
          return [String(m), h, geo.islandWindowRect(g, h)];
        }),
      });
    }
const out = join(root, 'apps/desktop-go/internal/core/island/testdata');
mkdirSync(out, { recursive: true });
writeFileSync(
  join(out, 'geometry.json'),
  JSON.stringify({
    cases,
    pages: Object.entries(pages).map(([g, p]) => ({ g: JSON.parse(g), html: p.html })),
  }) + '\n',
);
console.log('island geometry: cases', cases.length, 'pages', Object.keys(pages).length);
