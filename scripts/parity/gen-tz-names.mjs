// D-B9-4：从 Node（V8/ICU）生成 IANA → [标准, 夏令] 时区长名表，嵌入 Go（internal/core/tts/edge/zonenames_gen.go）
// 用法（用 v2.0.4 实际运行时 Electron 44.9.3）：ELECTRON_RUN_AS_NODE=1 electron scripts/parity/gen-tz-names.mjs > apps/desktop-go/internal/core/tts/edge/zonenames_gen.go && gofmt -w apps/desktop-go/internal/core/tts/edge/zonenames_gen.go
import { readdirSync, statSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const names = new Set(Intl.supportedValuesOf('timeZone'));
names.add('UTC');
const root = '/usr/share/zoneinfo';
const walk = (d, pre) => {
  for (const f of readdirSync(d)) {
    if (/^(posix|right|SystemV)$/.test(f) || /\.(tab|zi|list)$/.test(f) || /^[a-z+]/.test(f)) continue;
    const p = join(d, f);
    const s = statSync(p);
    if (s.isDirectory()) walk(p, pre + f + '/');
    else if (readFileSync(p).subarray(0, 4).toString() === 'TZif') names.add(pre + f);
  }
};
try { walk(root, ''); } catch {}

// V8 Date#toString 括号名 = ICU TimeZone::getDisplayName(isDST, LONG)：只取决于该时刻 ICU 是否判夏令，
// 元区（metazone）与回退写法（GMT±hh:mm，按区当前 raw offset）都按“现在”定，与时刻无关。
// 故每区只有 [标准, 夏令] 两个名。ICU isDST ≈ tzdata isdst（rearguard：Dublin 冬季为标准，Go 读到的 vanguard 数据在此处取反）；
// Go 侧 icuIsDST 用同一规则（protocol.go）。在真实运行时（Electron 44.9.3）里逐月采样 1970–2037。
import { execFileSync } from 'node:child_process';
const probe = `const r=[];const off=(t)=>-new Date(t).getTimezoneOffset();for(let y=1970;y<2038;y++)for(let m=0;m<12;m++){const t=Date.UTC(y,m,15,12),d=new Date(t);const o=off(t),a=off(Date.UTC(y,m+6,15,12)),b=off(Date.UTC(y,m-6,15,12));r.push([t/1000,d.toString().match(/\\((.*)\\)$/)[1],o>a||o>b?1:(o===a&&o===b?2:0)])}process.stdout.write(JSON.stringify(r))`;
const rows = [];
for (const tz of [...names].sort()) {
  let r;
  try { r = JSON.parse(execFileSync(process.execPath, ['-e', probe], { env: { ...process.env, TZ: tz } }).toString()); } catch { continue; }
  // getDisplayName 只给两种名：按名字统计“偏移大于前/后半年”的比例，比例高者为夏令名
  const c = {};
  for (const [, n, k] of r) { c[n] ??= [0, 0]; c[n][0]++; if (k === 1) c[n][1]++; }
  const ns = Object.keys(c);
  if (ns.length > 2) throw new Error(`${tz}: >2 names ${ns}`);
  ns.sort((x, y) => c[x][1] / c[x][0] - c[y][1] / c[y][0]);
  const std = ns[0], dst = ns[ns.length - 1];
  rows.push(`\t${JSON.stringify(tz)}: {${JSON.stringify(std)}, ${JSON.stringify(dst)}},`);
}
process.stdout.write(`// Code generated by scripts/parity/gen-tz-names.mjs (Node ${process.version}, ICU ${process.versions.icu}); DO NOT EDIT.

package edge

// zoneNames：IANA → {标准名, 夏令名}（V8 Date#toString 括号内，ICU getDisplayName）
var zoneNames = map[string]zoneName{
${rows.join('\n')}
}
`);
