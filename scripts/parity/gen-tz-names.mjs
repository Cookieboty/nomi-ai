// D-B9-4：从 Node（V8/ICU）生成 IANA → [标准, 夏令] 时区长名表，嵌入 Go（internal/core/tts/edge/zonenames_gen.go）
// 用法：node scripts/parity/gen-tz-names.mjs > apps/desktop-go/internal/core/tts/edge/zonenames_gen.go && gofmt -w apps/desktop-go/internal/core/tts/edge/zonenames_gen.go
import { readdirSync, statSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const names = new Set(Intl.supportedValuesOf('timeZone'));
names.add('UTC');
const root = '/usr/share/zoneinfo';
const walk = (d, pre) => {
  for (const f of readdirSync(d)) {
    if (/^(posix|right|SystemV)$/.test(f) || /\.(tab|zi|list)$/.test(f) || /^[a-z+]/.test(f)) continue;
    const p = join(d, f);
    const s = statSync(p);
    if (s.isDirectory()) walk(p, pre + f + '/');
    else if (readFileSync(p).subarray(0, 4).toString() === 'TZif') names.add(pre + f);
  }
};
try { walk(root, ''); } catch {}

const long = (tz, d) => {
  try {
    return new Intl.DateTimeFormat('en-US', { timeZone: tz, timeZoneName: 'long' })
      .formatToParts(d).find((p) => p.type === 'timeZoneName').value;
  } catch { return null; }
};
const offset = (tz, d) => {
  const s = new Intl.DateTimeFormat('en-US', { timeZone: tz, timeZoneName: 'longOffset' })
    .formatToParts(d).find((p) => p.type === 'timeZoneName').value;
  const m = /GMT([+-])(\d\d):(\d\d)/.exec(s);
  return m ? (m[1] === '-' ? -1 : 1) * (+m[2] * 60 + +m[3]) : 0;
};
const jan = new Date(Date.UTC(2026, 0, 15, 12)), jul = new Date(Date.UTC(2026, 6, 15, 12));
const rows = [];
for (const tz of [...names].sort()) {
  const a = long(tz, jan), b = long(tz, jul);
  if (a == null || b == null) continue;
  const oa = offset(tz, jan), ob = offset(tz, jul);
  let std = a, dst = b;
  if (oa > ob) { std = b; dst = a; }
  if (oa === ob) {
    dst = std;
    // 当前无夏令：往回找最近一个有夏令的年份取夏令名（历史时间戳也能对上）
    for (let y = 2025; y >= 1970; y--) {
      const j = new Date(Date.UTC(y, 0, 15, 12)), l = new Date(Date.UTC(y, 6, 15, 12));
      const oj = offset(tz, j), ol = offset(tz, l);
      if (oj !== ol) { dst = long(tz, oj > ol ? j : l); break; }
    }
  }
  // ICU 回退写法（GMT / GMT±hh:mm）随实际偏移变化：存空串，Go 侧按偏移现算
  const fb = (n) => (/^GMT([+-]\d\d:\d\d)?$/.test(n) ? '' : n);
  std = fb(std); dst = fb(dst);
  if (!std && !dst) continue;
  rows.push(`\t${JSON.stringify(tz)}: {${JSON.stringify(std)}, ${JSON.stringify(dst)}},`);
}
process.stdout.write(`// Code generated by scripts/parity/gen-tz-names.mjs (Node ${process.version}, ICU ${process.versions.icu}); DO NOT EDIT.

package edge

// zoneNames：IANA → [标准, 夏令] 时区长名（V8 Date#toString 括号内，en-US / ICU long）
var zoneNames = map[string][2]string{
${rows.join('\n')}
}
`);
