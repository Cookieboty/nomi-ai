/**
 * Refresh the small, checked-in brand subset; no LobeHub package ships at runtime.
 * npm pack @lobehub/icons-static-svg@1.102.0, extract it, then:
 * node scripts/icons/update-brands.mjs /path/to/extracted/package
 * Also refreshes the standalone Go island's Tabler badges from the installed dependency.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { repoPath } from '@nomi-ai/repo-paths';

const source = process.argv[2];
if (!source) throw new Error('Pass the extracted @lobehub/icons-static-svg package directory.');
const version = '1.102.0';
if (JSON.parse(fs.readFileSync(path.join(source, 'package.json'), 'utf8')).version !== version) {
  throw new Error(`Expected @lobehub/icons-static-svg ${version}`);
}

// Provider marks and product marks are deliberately separate.
const selection = {
  openai: 'openai',
  anthropic: 'anthropic',
  claude: 'claude-color',
  claudecode: 'claudecode-color',
  codex: 'codex',
  'codex-color': 'codex-color',
  gemini: 'gemini-color',
  geminicli: 'geminicli',
  deepseek: 'deepseek-color',
  kimi: 'kimi-color',
  zhipu: 'zhipu-color',
  qwen: 'qwen-color',
  doubao: 'doubao-color',
  minimax: 'minimax-color',
  xai: 'xai',
  grok: 'grok',
  openrouter: 'openrouter',
  siliconcloud: 'siliconcloud-color',
  ollama: 'ollama',
  lmstudio: 'lmstudio',
};
const icons = {};
for (const [id, file] of Object.entries(selection)) {
  let svg = fs
    .readFileSync(path.join(source, 'icons', `${file}.svg`), 'utf8')
    .replace(/<title>.*?<\/title>/g, '')
    .replace(/\s(?:height|width)="1em"|\sstyle="[^"]*"/g, '')
    .trim();
  if (id === 'codex-color') {
    // The upstream colour asset includes a white avatar tile. Keep its original
    // gradient mark, removing the tile so sidebar Agent icons stay transparent.
    svg = svg
      .replace(/<path[^>]*fill="#fff"[^>]*><\/path>/, '')
      .replace('viewBox="0 0 24 24"', 'viewBox="3 3 18 18"');
  }
  if (/<(?:script|foreignObject)|\bon\w+=|`|\$\{|https?:\/\/(?!www\.w3\.org)/i.test(svg)) {
    throw new Error(`Unexpected active or remote SVG content: ${id}`);
  }
  // Kimi mixes a theme-sensitive K with a blue dot. Mask the K, then overlay
  // the original fixed-colour layer so the accent is preserved in both themes.
  const mixed = file.endsWith('-color') && svg.includes('currentColor');
  icons[id] = {
    svg,
    mono: !file.endsWith('-color') || mixed,
    ...(mixed ? { colorSvg: svg.replaceAll('currentColor', 'transparent') } : {}),
  };
}
// No Amux mark is available in LobeHub; retain the project's existing asset.
icons.amux = {
  mono: true,
  svg: '<svg fill="currentColor" viewBox="4 -3 120 120" xmlns="http://www.w3.org/2000/svg"><path d="M4 96 C4 96, 24 12, 64 12 C104 12, 124 96, 124 96 Q124 102, 118 102 C94 102, 92 64, 64 64 C36 64, 34 102, 10 102 Q4 102, 4 96 Z"></path></svg>',
};
const header = `/**
 * Generated by scripts/icons/update-brands.mjs; do not edit.
 * @lobehub/icons-static-svg ${version} · MIT · Copyright (c) 2023 LobeHub.
 * Logos belong to their respective owners. Amux retains the existing local asset.
 */
export interface BrandSvg {
  svg: string;
  mono: boolean;
  /** Fixed-colour accents layered over a theme-sensitive monochrome mark. */
  colorSvg?: string;
}

`;
fs.writeFileSync(
  repoPath('packages/ui/src/brand/icons.ts'),
  `${header}export const BRAND_ICONS: Readonly<Record<string, BrandSvg>> = ${JSON.stringify(icons, null, 2)};\n`,
);

const endpointBrands = {
  claude: 'claudecode',
  codex: 'codex-color',
  dsh: 'deepseek',
  grok: 'grok',
  gemini: 'gemini',
  kimi: 'kimi',
  minimax: 'minimax',
};
const ep = Object.fromEntries(Object.entries(endpointBrands).map(([key, id]) => [key, icons[id]]));
const islandFile = repoPath('apps/desktop-go/internal/core/island/island.html');
let island = fs.readFileSync(islandFile, 'utf8');
const start = island.indexOf('      // agent 的图标块');
const end = island.indexOf('      // 角标：', start);
if (start < 0 || end < 0) throw new Error('Missing island brand section markers');
const section = `      // agent 的图标块（由 scripts/icons/update-brands.mjs 生成；LobeHub ${version}，MIT）
      const EP = JSON.parse(String.raw\`${JSON.stringify(ep)}\`);
      function epTile(ep) {
        const mark = EP[ep];
        const s = h('span', 'ep');
        s.setAttribute('aria-hidden', 'true');
        const uri = svg => 'url("data:image/svg+xml;utf8,' + encodeURIComponent(svg) + '")';
        if (mark.mono) {
          Object.assign(s.style, { backgroundColor: 'currentColor', maskImage: uri(mark.svg), WebkitMaskImage: uri(mark.svg) });
          if (mark.colorSvg) {
            const accent = h('span', 'ep-accent');
            accent.style.backgroundImage = uri(mark.colorSvg);
            s.append(accent);
          }
        } else s.style.backgroundImage = uri(mark.svg);
        return s;
      }
`;
island = island.slice(0, start) + section + island.slice(end);

const tablerDir = path.resolve(
  path.dirname(fileURLToPath(import.meta.resolve('@tabler/icons-react'))),
  '../esm/icons',
);
const badges = {
  done: 'Check',
  failed: 'ExclamationMark',
  attention: 'ExclamationMark',
  approval: 'ExclamationMark',
  running: 'Loader2',
  message: 'Heart',
  reminder: 'ClockHour4',
  close: 'X',
};
const nodes = Object.fromEntries(
  Object.entries(badges).map(([id, icon]) => {
    const code = fs.readFileSync(path.join(tablerDir, `Icon${icon}.mjs`), 'utf8');
    const node = JSON.parse(code.match(/const __iconNode = (.+);/)[1]);
    return [id, node.map(([tag, { key: _key, ...attrs }]) => [tag, attrs])];
  }),
);
const badgeStart = island.indexOf('      // 角标图标');
const badgeEnd = island.indexOf('      function icon(', badgeStart);
if (badgeStart < 0 || badgeEnd < 0) throw new Error('Missing island badge section markers');
island =
  island.slice(0, badgeStart) +
  `      // 角标图标（Tabler 3.52.0，MIT；按需静态提取）\n      const ICON = ${JSON.stringify(nodes)};\n` +
  island.slice(badgeEnd);
fs.writeFileSync(islandFile, island);
console.log(`Updated ${Object.keys(icons).length} brand assets and the standalone island.`);
