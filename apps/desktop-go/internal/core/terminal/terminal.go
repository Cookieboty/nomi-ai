func NodePlatform() string {
	if runtime.GOOS == "windows" {
		return "win32"
	}
	return runtime.GOOS
}

func CommandName(kind, platform string) string {
	if platform == "win32" {
		return "nomi-" + kind + ".cmd"
	}
	return "nomi-" + kind
}

// ScriptInput：buildScript 入参
type ScriptInput struct {
	Kind, Platform, URL, TokenFile string
	Model                          *string
	Launch                         *gwagents.Launch
	Template                       *string
}

func (i *ScriptInput) obj() *u.Obj {
	o := u.NewObj("kind", i.Kind, "platform", i.Platform, "url", i.URL, "tokenFile", i.TokenFile)
	if i.Model != nil {
		o.Set("model", *i.Model)
	} else {
		o.Set("model", nil)
	}
	if i.Launch != nil {
		o.Set("launch", i.Launch.Obj())
	}
	if i.Template != nil {
		o.Set("template", *i.Template)
	}
	return o
}

var shArgRe = regexp.MustCompile(`^[A-Za-z0-9_@%+=:,./-]+$`)

func shArg(s string) string {
	if shArgRe.MatchString(s) {
		return s
	}
	return sh.ShQuote(s)
}

func header(kind string) string {
	return `Generated by Nomi for "` + kind + `" (third-party models via the Nomi gateway). ` +
		"Regenerated automatically; edits are overwritten."
}

func posixDirname(p string) string {
	// path.dirname（POSIX 平台调用）
	return filepath.Dir(p)
}

func posixScript(i *ScriptInput) string {
	bin := i.Kind
	say := func(msg string) string { return `printf '%s\n' ` + sh.ShQuote(msg) + " >&2" }
	L := []string{"#!/bin/sh", "# " + header(i.Kind)}
	if i.Model == nil || i.Launch == nil {
		L = append(L, say(i18n.T("electron.common.no-third-party-model-is-set-for-choose", bin)), "exit 1")
		return strings.Join(L, "\n") + "\n"
	}
	l := i.Launch
	model := *i.Model
	needModel := say(i18n.T("electron.common.nomi-model-must-be-followed-by-provider-model"))
	badModel := say(i18n.T("electron.common.invalid-model-name-prefix"))
	down := say(i18n.T("electron.common.please-start-nomi-first-the-gateway-is-not", i.URL))
	noToken := say(i18n.T("electron.common.token-not-found-turn-terminal-commands-off-and"))
	noBin := say(i18n.T("electron.common.was-not-found-please-install-it-first", bin))
	L = append(L,
		"NOMI_URL="+sh.ShQuote(i.URL), "NOMI_TOKEN_FILE="+sh.ShQuote(i.TokenFile), "NOMI_DEFAULT_MODEL="+sh.ShQuote(model),
		"NOMI_MODEL=$NOMI_DEFAULT_MODEL", "NOMI_DOWN=", "",
		"# --nomi-model provider/model overrides the model; every other argument is passed through",
		"n=$#", `while [ "$n" -gt 0 ]; do`, "  a=$1; shift; n=$((n - 1))", "  case $a in", "    --nomi-model)",
		`      if [ "$n" -eq 0 ]; then `+needModel+"; exit 2; fi",
		"      NOMI_MODEL=$1; shift; n=$((n - 1)) ;;", "    --nomi-model=*) NOMI_MODEL=${a#--nomi-model=} ;;",
		`    *) set -- "$@" "$a" ;;`, "  esac", "done", "case $NOMI_MODEL in",
		"  ''|"+modelReSh+") "+badModel+`; printf '%s\n' "$NOMI_MODEL" >&2; exit 2 ;;`, "esac", "",
		"# Is Nomi (the gateway) running?", "if command -v curl >/dev/null 2>&1; then",
		`  curl -fsS -m 3 "$NOMI_URL/health" >/dev/null 2>&1 || NOMI_DOWN=1`, "elif command -v wget >/dev/null 2>&1; then",
		`  wget -q -T 3 -O /dev/null "$NOMI_URL/health" >/dev/null 2>&1 || NOMI_DOWN=1`, "fi",
		`if [ -n "$NOMI_DOWN" ]; then`, "  "+down, "  exit 1", "fi",
		`if [ ! -r "$NOMI_TOKEN_FILE" ]; then`, "  "+noToken, "  exit 1", "fi",
		`NOMI_TOKEN=$(cat "$NOMI_TOKEN_FILE")`,
		"if ! command -v "+bin+" >/dev/null 2>&1; then", "  "+noBin, "  exit 127", "fi", "",
	)
	if len(l.Strip) > 0 {
		L = append(L, "unset "+strings.Join(l.Strip, " "))
	}
	for _, e := range l.Env {
		switch {
		case strings.Contains(e.V, tokenMark):
			L = append(L, "export "+e.K+`="$NOMI_TOKEN"`)
		case e.V == model:
			L = append(L, "export "+e.K+`="$NOMI_MODEL"`)
		default:
			L = append(L, "export "+e.K+"="+sh.ShQuote(e.V))
		}
	}
	args := []string{}
	for _, a := range l.Args {
		args = append(args, shArg(a))
	}
	if i.Kind == "claude" {
		args = append(args, "--model", `"$NOMI_MODEL"`)
	}
	if i.Kind == "codex" {
		args = append(args, "-c", `"model=\"$NOMI_MODEL\""`)
	}
	slug := `$(printf '%s' "$NOMI_MODEL" | tr -c 'A-Za-z0-9._-' '_')`
	if i.Kind == "dsh" && i.Template != nil && *i.Template != "" {
		patchAt := indexOf(l.Args, "--patch") + 1
		base := ""
		if patchAt < len(l.Args) {
			base = l.Args[patchAt]
		}
		L = append(L, "NOMI_PATCH="+sh.ShQuote(base), `if [ "$NOMI_MODEL" != "$NOMI_DEFAULT_MODEL" ]; then`,
			"  NOMI_PATCH="+sh.ShQuote(posixDirname(base)+"/override-")+slug+".yml",
			`  sed "s|`+modelMark+`|$NOMI_MODEL|g" `+sh.ShQuote(*i.Template)+` > "$NOMI_PATCH" || exit 1`,
			`  chmod 600 "$NOMI_PATCH"`, "fi")
		if patchAt > 0 {
			for len(args) <= patchAt {
				args = append(args, "")
			}
			args[patchAt] = `"$NOMI_PATCH"`
		}
	}
	if i.Kind == "grok" && i.Template != nil && *i.Template != "" {
		home, _ := l.EnvGet("GROK_HOME")
		L = append(L, `if [ "$NOMI_MODEL" != "$NOMI_DEFAULT_MODEL" ]; then`,
			"  NOMI_HOME="+sh.ShQuote(home+"-models/")+slug,
			`  mkdir -p "$NOMI_HOME" && chmod 700 "$NOMI_HOME" || exit 1`,
			"  for f in "+sh.ShQuote(home)+"/* "+sh.ShQuote(home)+"/.[!.]*; do",
			`    [ -e "$f" ] || [ -L "$f" ] || continue`, "    b=${f##*/}", "    [ \"$b\" = config.toml ] && continue",
			`    [ -e "$NOMI_HOME/$b" ] || [ -L "$NOMI_HOME/$b" ] && continue`,
			`    t=$(readlink "$f" 2>/dev/null) || t=$f`, `    ln -s "$t" "$NOMI_HOME/$b" 2>/dev/null`, "  done",
			`  sed "s|`+modelMark+`|$NOMI_MODEL|g" `+sh.ShQuote(*i.Template)+` > "$NOMI_HOME/config.toml" || exit 1`,
			`  chmod 600 "$NOMI_HOME/config.toml"`, `  export GROK_HOME="$NOMI_HOME"`, "fi")
	}
	L = append(L, "exec "+strings.Join(append([]string{bin}, args...), " ")+` "$@"`)
	return strings.Join(L, "\n") + "\n"
}

func indexOf(xs []string, s string) int {
	for i, x := range xs {
		if x == s {
			return i
		}
	}
	return -1
}

func cmdScript(i *ScriptInput) string {
	return strings.Join([]string{"@echo off", "rem " + header(i.Kind), "setlocal DisableDelayedExpansion",
		`node.exe "%~dp0nomi-runner.cjs" "%~dp0nomi-` + i.Kind + `.json" %*`, "exit /b %ERRORLEVEL%", ""}, "\r\n")
}

func powershellScript(kind string) string {
	return strings.Join([]string{"# " + header(kind), "$nomiPreviousArgs = $env:NOMI_TERMINAL_ARGS", "try {",
		"  $env:NOMI_TERMINAL_ARGS = ConvertTo-Json -InputObject @($args) -Compress",
		"  & node.exe (Join-Path $PSScriptRoot 'nomi-runner.cjs') (Join-Path $PSScriptRoot 'nomi-" + kind + ".json') --nomi-powershell-args",
		"  $nomiExitCode = $LASTEXITCODE", "} finally {", "  $env:NOMI_TERMINAL_ARGS = $nomiPreviousArgs", "}",
		"exit $nomiExitCode", ""}, "\r\n")
}

func BuildScript(i *ScriptInput) string {
	if i.Platform == "win32" {
		return cmdScript(i)
	}
	return posixScript(i)
}

func AddRcBlock(content, shell string) string {
	line := `export PATH="$HOME/.nomi/bin:$PATH"`
	if shell == "fish" {
		line = "set -gx PATH $HOME/.nomi/bin $PATH"
	}
	kept := RemoveRcBlock(content)
	sep := ""
	if kept != "" && !strings.HasSuffix(kept, "\n") {
		sep = "\n"
	}
	return kept + sep + RcBegin + "\n# Added by Nomi; removed when terminal commands are turned off.\n" + line + "\n" + RcEnd + "\n"
}

func RemoveRcBlock(content string) string {
	out := []string{}
	in := false
	for _, l := range strings.Split(content, "\n") {
		if !in && u.JSTrim(l) == RcBegin {
			in = true
			continue
		}
		if in {
			if u.JSTrim(l) == RcEnd {
				in = false
			}
			continue
		}
		out = append(out, l)
	}
	if in {
		return content
	}
	return strings.Join(out, "\n")
}
